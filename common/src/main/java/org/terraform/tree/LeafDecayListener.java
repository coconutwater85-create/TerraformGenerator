package org.terraform.tree;

import org.bukkit.Bukkit;
import org.bukkit.Material;
import org.bukkit.Tag;
import org.bukkit.World;
import org.bukkit.block.Block;
import org.bukkit.block.data.type.Leaves;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;
import org.bukkit.event.block.BlockBreakEvent;
import org.bukkit.event.block.LeavesDecayEvent;
import org.jetbrains.annotations.NotNull;
import org.terraform.coregen.bukkit.TerraformGenerator;
import org.terraform.main.TerraformGeneratorPlugin;
import org.terraform.tree.LeafDecaySolver.Cell;
import org.terraform.tree.LeafDecaySolver.Pos;

import java.util.Set;
import java.util.concurrent.ThreadLocalRandom;

/**
 * Makes leaves decay when the tree holding them is cut down.
 * <p>
 * Vanilla only decays a leaf once no log is within 6 blocks of it, and does so slowly.
 * TerraformGenerator trees have thick branches, so after the trunk is cut, floating
 * branch logs hold the canopy up forever. See {@link LeafDecaySolver} for the rule used here.
 * <p>
 * Only leaves that are allowed to decay are touched. Leaves placed by players are persistent and are left alone.
 * Only worlds generated by TerraformGenerator are affected.
 * <p>
 * Only breaking logs by hand/tool is handled (BlockBreakEvent). Logs that are burnt or blown up
 * are left to vanilla decay.
 */
public class LeafDecayListener implements Listener {

    /**
     * Leaves decay one by one, spread over this many ticks. A whole canopy vanishing in the
     * same tick would spawn hundreds of drops at once.
     */
    private static final int MIN_DELAY_TICKS = 10;
    private static final int MAX_DELAY_TICKS = 160;

    @EventHandler(priority = EventPriority.MONITOR, ignoreCancelled = true)
    public void onLogBreak(@NotNull BlockBreakEvent event) {
        Block broken = event.getBlock();
        if (!Tag.LOGS.isTagged(broken.getType())) {
            return;
        }

        World world = broken.getWorld();
        if (!(world.getGenerator() instanceof TerraformGenerator)) {
            return;
        }

        // This runs before the log is actually removed. The solver treats it as already gone.
        Set<Pos> orphans = LeafDecaySolver.findOrphanedLeaves(
                (x, y, z) -> classify(world, x, y, z),
                new Pos(broken.getX(), broken.getY(), broken.getZ())
        );

        for (Pos leaf : orphans) {
            int delay = ThreadLocalRandom.current().nextInt(MIN_DELAY_TICKS, MAX_DELAY_TICKS + 1);
            TerraformGeneratorPlugin.taskScheduler.execRegionLater(world,
                    leaf.x() >> 4, leaf.z() >> 4,
                    () -> decay(world, leaf),
                    delay
            );
        }
    }

    private static @NotNull Cell classify(@NotNull World world, int x, int y, int z) {
        if (y < world.getMinHeight()) {
            return Cell.SOLID;
        }
        if (y >= world.getMaxHeight()) {
            return Cell.EMPTY;
        }
        // Never load chunks just to look at them. Unknown ground is treated as solid, as it is
        // safer to leave leaves alone than to remove them.
        if (!world.isChunkLoaded(x >> 4, z >> 4)) {
            return Cell.SOLID;
        }

        Block block = world.getBlockAt(x, y, z);
        Material type = block.getType();
        if (Tag.LOGS.isTagged(type)) {
            return Cell.LOG;
        }
        if (Tag.LEAVES.isTagged(type)) {
            // Persistent leaves never decay, so they are not ours to touch.
            if (block.getBlockData() instanceof Leaves leaves && leaves.isPersistent()) {
                return Cell.SOLID;
            }
            return Cell.LEAF;
        }
        return type.isSolid() ? Cell.SOLID : Cell.EMPTY;
    }

    private static void decay(@NotNull World world, @NotNull Pos pos) {
        if (!world.isChunkLoaded(pos.x() >> 4, pos.z() >> 4)) {
            return; // Vanilla will deal with it when it loads.
        }

        Block block = world.getBlockAt(pos.x(), pos.y(), pos.z());
        if (!Tag.LEAVES.isTagged(block.getType())) {
            return; // Already gone.
        }
        if (block.getBlockData() instanceof Leaves leaves && leaves.isPersistent()) {
            return;
        }

        // Same as vanilla decay, other plugins get to cancel it.
        LeavesDecayEvent decayEvent = new LeavesDecayEvent(block);
        Bukkit.getPluginManager().callEvent(decayEvent);
        if (decayEvent.isCancelled()) {
            return;
        }
        block.breakNaturally();
    }
}
